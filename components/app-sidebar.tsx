"use client";

import { BarChart3, Bot, Radar, Footprints, Users } from "lucide-react";
import Link from "next/link";
import { usePathname } from "next/navigation";
import {
  Sidebar,
  SidebarContent,
  SidebarFooter,
  SidebarGroup,
  SidebarGroupContent,
  SidebarHeader,
  SidebarMenu,
  SidebarMenuBadge,
  SidebarMenuButton,
  SidebarMenuItem,
} from "@/components/ui/sidebar";
import { CHAIN, STORES } from "@/lib/domain/catalog";

const NAV = [
  { title: "Live", href: `/stores/${STORES[0].id}`, match: "/stores", icon: Radar },
  { title: "Analytics", href: "/analytics", match: "/analytics", icon: BarChart3, soon: true },
  { title: "Visits", href: "/visits", match: "/visits", icon: Footprints, soon: true },
  { title: "Customers", href: "/customers", match: "/customers", icon: Users, soon: true },
  { title: "Assistant", href: "/assistant", match: "/assistant", icon: Bot, soon: true },
];

export function AppSidebar() {
  return (
    <Sidebar collapsible="icon">
      <SidebarHeader>
        <SidebarMenu>
          <SidebarMenuItem>
            <SidebarMenuButton size="lg" render={<Link href="/" />}>
              <span className="bg-primary text-primary-foreground flex aspect-square size-8 items-center justify-center rounded-lg">
                <Radar className="size-4" />
              </span>
              <span className="grid flex-1 text-left leading-tight">
                <span className="font-semibold">Store Radar</span>
                <span className="text-muted-foreground text-xs">
                  {CHAIN.name} · {STORES.length} stores
                </span>
              </span>
            </SidebarMenuButton>
          </SidebarMenuItem>
        </SidebarMenu>
      </SidebarHeader>
      <SidebarContent>
        <SidebarGroup>
          <SidebarGroupContent>
            <NavMenu />
          </SidebarGroupContent>
        </SidebarGroup>
      </SidebarContent>
      <SidebarFooter className="text-muted-foreground px-4 pb-4 text-xs group-data-[collapsible=icon]:hidden">
        Fictional data, generated by code.
      </SidebarFooter>
    </Sidebar>
  );
}

function NavMenu() {
  const pathname = usePathname();
  return (
    <SidebarMenu>
      {NAV.map((item) => (
        <SidebarMenuItem key={item.title}>
          {item.soon ? (
            <SidebarMenuButton disabled tooltip={`${item.title} (coming soon)`} className="opacity-60">
              <item.icon />
              <span>{item.title}</span>
            </SidebarMenuButton>
          ) : (
            <SidebarMenuButton
              isActive={pathname.startsWith(item.match)}
              tooltip={item.title}
              render={<Link href={item.href} />}
            >
              <item.icon />
              <span>{item.title}</span>
            </SidebarMenuButton>
          )}
          {item.soon && <SidebarMenuBadge>Soon</SidebarMenuBadge>}
        </SidebarMenuItem>
      ))}
    </SidebarMenu>
  );
}
